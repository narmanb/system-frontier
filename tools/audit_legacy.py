#!/usr/bin/env python3
"""Analysis-only audit of the legacy HTML reference build.

Usage: python3 -I tools/audit_legacy.py legacy/<file>.html build/analysis [docs/OVERRIDE_INVENTORY.md]

Writes (to the output dir, which is git-ignored):
  scripts/NN_<id>.js     each <script> block, verbatim
  images/<sha12>.<ext>   decoded embedded data-URL images (bytes untouched)
  symbols.json           function definitions/reassignments per block
  images.json            image manifest (hash, size, dims, source line, context)
Never used by the game runtime.
"""
import base64, hashlib, json, re, struct, sys, pathlib

def png_dims(b):
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", b[16:24])
    if b[:6] in (b"GIF87a", b"GIF89a"):
        return struct.unpack("<HH", b[6:10])
    return (None, None)

def main(src, out):
    src = pathlib.Path(src); out = pathlib.Path(out)
    text = src.read_text(encoding="utf-8")
    raw = src.read_bytes()
    (out / "scripts").mkdir(parents=True, exist_ok=True)
    (out / "images").mkdir(parents=True, exist_ok=True)
    lines = text.split("\n")
    # --- scripts
    blocks = []
    for m in re.finditer(r"<script([^>]*)>(.*?)</script>", text, re.S):
        attrs, body = m.group(1), m.group(2)
        sid = (re.search(r'id="([^"]+)"', attrs) or [None, "main"])[1]
        line = text.count("\n", 0, m.start()) + 1
        n = len(blocks)
        name = f"{n:02d}_{sid}.js"
        (out / "scripts" / name).write_text(body, encoding="utf-8")
        blocks.append({"index": n, "id": sid, "start_line": line, "file": name})
    # --- symbols: declarations and reassignments
    decl = re.compile(r"(?<![\w.])function\s+([A-Za-z_$][\w$]*)\s*\(")
    reassign = re.compile(r"(?<![\w.$])([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?(?:function\b|\([^()]*\)\s*=>|[A-Za-z_$][\w$]*\s*=>)")
    winassign = re.compile(r"window\.([A-Za-z_$][\w$]*)\s*=")
    symbols = {}
    for b in blocks:
        body = (out / "scripts" / b["file"]).read_text(encoding="utf-8")
        for kind, rx in (("declare", decl), ("reassign", reassign), ("window", winassign)):
            for m in rx.finditer(body):
                nm = m.group(1)
                if kind == "reassign" and nm in ("const", "let", "var"):
                    continue
                pre = body[max(0, m.start()-6):m.start()]
                if kind == "reassign" and re.search(r"(const|let|var)\s*$", pre):
                    kind2 = "local"
                else:
                    kind2 = kind
                ln = b["start_line"] + body.count("\n", 0, m.start())
                symbols.setdefault(nm, []).append({"block": b["index"], "block_id": b["id"], "line": ln, "kind": kind2})
    overrides = {k: v for k, v in symbols.items()
                 if len({e["block"] for e in v}) > 1 or sum(e["kind"] in ("declare", "reassign", "window") for e in v) > 1}
    # --- images
    imgs, seen = [], {}
    for m in re.finditer(r"data:(image/[a-z+]+);base64,([A-Za-z0-9+/=]+)", text):
        data = base64.b64decode(m.group(2))
        h = hashlib.sha256(data).hexdigest()
        ext = m.group(1).split("/")[1].replace("+xml", "")
        line = text.count("\n", 0, m.start()) + 1
        ctx = text[max(0, m.start()-160):m.start()].split("\n")[-1][-120:]
        w, hgt = png_dims(data)
        if h not in seen:
            (out / "images" / f"{h[:12]}.{ext}").write_bytes(data)
            seen[h] = {"sha256": h, "file": f"images/{h[:12]}.{ext}", "mime": m.group(1),
                       "bytes": len(data), "width": w, "height": hgt, "occurrences": []}
            imgs.append(seen[h])
        seen[h]["occurrences"].append({"line": line, "context": ctx})
    (out / "symbols.json").write_text(json.dumps({"blocks": blocks, "overrides": overrides, "all": symbols}, indent=1))
    (out / "images.json").write_text(json.dumps(imgs, indent=1))
    print(f"sha256 {hashlib.sha256(raw).hexdigest()}  bytes {len(raw)}  lines {len(lines)}")
    print(f"{len(blocks)} script blocks, {len(symbols)} symbols, {len(overrides)} multiply-defined")
    print(f"{len(imgs)} unique images from {sum(len(i['occurrences']) for i in imgs)} data URLs")

def write_inventory(out, md_path):
    d = json.loads((pathlib.Path(out) / "symbols.json").read_text())
    blocks = {b["index"]: b for b in d["blocks"]}
    lines = ["# Legacy override inventory", "",
             "Generated by `tools/audit_legacy.py` from the frozen v7.2.4 reference. Each row is a",
             "function defined more than once; **the last definition is the effective one** (later",
             "`<script>` blocks reassign earlier globals). Wrappers that call the previous version are",
             "noted where they matter in docs/PARITY_MATRIX.md. Line numbers refer to the legacy file.", "",
             "| Symbol | Definitions (block:line) | Effective (final) |", "|---|---|---|"]
    for name, defs in sorted(d["overrides"].items()):
        defs = [e for e in defs if e["kind"] in ("declare", "reassign", "window")]
        if len(defs) < 2:
            continue
        chain = " → ".join(f"{e['block']}:{e['line']}" for e in defs)
        last = defs[-1]
        lines.append(f"| `{name}` | {chain} | block {last['block']} `{blocks[last['block']]['id']}` line {last['line']} |")
    lines += ["", "## Script blocks", "", "| # | id | starts at line |", "|---|---|---|"]
    for b in d["blocks"]:
        lines.append(f"| {b['index']} | `{b['id']}` | {b['start_line']} |")
    pathlib.Path(md_path).write_text("\n".join(lines) + "\n")
    print("wrote", md_path)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
    if len(sys.argv) > 3:
        write_inventory(sys.argv[2], sys.argv[3])
